import { supabase, isSupabaseConfigured } from './supabase.js';
import { benchmarkValues, getProduct, pickBestItem, remittanceCostPct } from './benchmark.js';

/* Thin, cached data-access layer over the Supabase rate tables.
   Every reader returns null when Supabase isn't configured so callers can respond
   with a clear "not configured" error. */

const TTL_MS = 5 * 60 * 1000;
const cache = new Map(); // key -> { at, value }

async function cached(key, loader) {
  const hit = cache.get(key);
  if (hit && Date.now() - hit.at < TTL_MS) return hit.value;
  const value = await loader();
  cache.set(key, { at: Date.now(), value });
  return value;
}

export const ratesConfigured = isSupabaseConfigured;

/* Provenance policy. Rows in the rate tables are either REAL (sourced from a
   regulator feed or a published rate sheet, is_indicative = false) or
   INDICATIVE (generated by scripts/seed-rates.mjs to give the app something to
   render before real coverage existed, is_indicative = true).

   Nothing downstream could tell them apart, so a generated figure was being
   presented to users as a benchmark with a named bank behind it. Real-only is
   therefore the default: a pool with no sourced rows now returns "no data yet"
   rather than a plausible invention.

   Set RATES_REAL_ONLY=false to serve indicative rows again (they are then
   labelled `dataQuality: 'indicative'` in the response — never unmarked). */
export const REAL_ONLY = String(process.env.RATES_REAL_ONLY ?? 'true').toLowerCase() !== 'false';

export async function getCountries() {
  if (!isSupabaseConfigured) return null;
  return cached('countries', async () => {
    const { data, error } = await supabase
      .from('countries')
      .select('code, name, currency, currency_symbol')
      .order('display_order');
    if (error) throw error;
    return data;
  });
}

/* Aggregate market-reference rates (from public.market_rates, populated by
   `npm run market:fetch`). Returns { product -> { value, unit, source, as_of } }
   for the 'market_typical' metric. Never throws — an empty/missing table just
   means no reference is shown. */
export async function getMarketReference(country = 'SG') {
  if (!isSupabaseConfigured) return {};
  return cached(`market:${country}`, async () => {
    try {
      const { data, error } = await supabase
        .from('market_rates')
        .select('product, value, unit, source, as_of')
        .eq('country_code', country)
        .eq('metric', 'market_typical');
      if (error) return {};
      const map = {};
      for (const r of data || []) map[r.product] = { value: Number(r.value), unit: r.unit, source: r.source, asOf: r.as_of };
      return map;
    } catch {
      return {};
    }
  });
}

export async function getBanks(country) {
  if (!isSupabaseConfigured) return null;
  return cached(`banks:${country}`, async () => {
    let q = supabase.from('banks').select('id, name, category, country_code').order('display_order');
    if (country) q = q.eq('country_code', country);
    const { data, error } = await q;
    if (error) throw error;
    return data;
  });
}

const BANK_JOIN = 'banks!inner(id, name, category, country_code)';

export async function getOverdraft(country, currency) {
  if (!isSupabaseConfigured) return null;
  return cached(`od:${country}:${currency || ''}`, async () => {
    let q = supabase.from('overdraft_rates').select(`rate_min, rate_max, currency, ${BANK_JOIN}`);
    if (country) q = q.eq('banks.country_code', country);
    if (currency) q = q.eq('currency', currency);
    const { data, error } = await q;
    if (error) throw error;
    return data;
  });
}

export async function getRemittance(country, direction) {
  if (!isSupabaseConfigured) return null;
  return cached(`rem:${REAL_ONLY ? 'r' : 'a'}:${country}:${direction || ''}`, async () => {
    let q = supabase
      .from('remittance_charges')
      .select(`direction, counterparty, amount, amount_currency, upfront_fee, intermediary_fee, lifting_fee, fee_currency, fx_spread_pct, is_indicative, ${BANK_JOIN}`);
    if (country) q = q.eq('banks.country_code', country);
    if (direction) q = q.eq('direction', direction);
    if (REAL_ONLY) q = q.eq('is_indicative', false);
    const { data, error } = await q;
    if (error) throw error;
    return data;
  });
}

