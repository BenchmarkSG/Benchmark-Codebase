/* Unified rate pool. Every 'rate'-family product (loans, deposits, current
   account, overdraft, short-term & unfunded facilities) lives in product_rates,
   keyed by product id + optional `variant` (funded/unfunded type). */
/* How each rate was published — 'exact', 'range' (rate is the midpoint; the
   bounds ride along) or 'from' (a floor). Added by supabase/rate_basis.sql. A
   database that predates that migration has no such columns; rather than take
   every rate endpoint down, the first 42703 (undefined column) switches this
   process to the legacy column list and reports every row as exact — which,
   for rows written before the migration, is what they are. */
const PR_COLS = 'bank, currency, rate, rate_type, variant, is_indicative';
const PR_BASIS_COLS = `${PR_COLS}, rate_basis, rate_low, rate_high`;
const PR_FLOAT_COLS = `${PR_BASIS_COLS}, rate_index, index_value, spread`;

/* Column sets, widest first. A database that predates supabase/rate_basis.sql or
   supabase/floating_rate.sql has no such columns; rather than take every rate
   endpoint down, the first 42703 (undefined column) drops this process to the
   next-narrowest set for good, filling the absent fields with what they mean for
   a row written before that migration — a single published figure, on a fixed
   rate, which for those rows is exactly what it is. */
const COL_SETS = [
  { cols: PR_FLOAT_COLS, missing: {} },
  { cols: PR_BASIS_COLS, needs: 'floating_rate.sql', missing: { rate_index: null, index_value: null, spread: null } },
  { cols: PR_COLS, needs: 'rate_basis.sql', missing: { rate_basis: 'exact', rate_low: null, rate_high: null, rate_index: null, index_value: null, spread: null } },
];
let tier = 0;

async function selectProductRates(build) {
  for (; tier < COL_SETS.length; tier++) {
    const { cols, missing } = COL_SETS[tier];
    const { data, error } = await build(cols);
    if (!error) return (data || []).map((r) => ({ ...missing, ...r }));
    if (error.code !== '42703') throw error;
    const next = COL_SETS[tier + 1];
    console.warn(next
      ? `[rates] product_rates is missing columns — run supabase/${next.needs}; serving without them until then`
      : '[rates] product_rates is missing its core columns — run supabase/product_rates.sql');
  }
  throw new Error('product_rates is missing expected columns — see PRODUCT_DATA.md');
}

export async function getGenericRates(country, product, currency, variant) {
  if (!isSupabaseConfigured) return null;
  return cached(`pr:${REAL_ONLY ? 'r' : 'a'}:${country}:${product}:${currency || ''}:${variant || ''}`, () =>
    selectProductRates((cols) => {
      let q = supabase.from('product_rates').select(cols)
        .eq('country_code', country).eq('product', product);
      if (currency) q = q.eq('currency', currency);
      if (variant) q = q.eq('variant', variant);
      if (REAL_ONLY) q = q.eq('is_indicative', false);
      return q;
    }));
}

/* Cross-border: turn each bank's remittance row into an all-in cost % (FX spread
   plus fees expressed as a % of the notional) so it's comparable to the user's
   computed cost. Benchmarks the outgoing leg. */
export async function getCrossBorderCostPool(country, { counterparty = null, sentAmount = 0, sendCurrency = null } = {}) {
  if (!isSupabaseConfigured) return null;
  let rows = await getRemittance(country, 'outgoing');
  // A corridor is part of the comparison: a bank's USD spread says nothing
  // about its INR spread. Sourced rows carry the receive currency as
  // `counterparty`; when the caller names one, only that corridor competes.
  if (counterparty) rows = (rows || []).filter((x) => String(x.counterparty).toUpperCase() === String(counterparty).toUpperCase());
  const items = (rows || []).map((x) => ({
    bank: x.banks?.name || null,
    value: remittanceCostPct(x, { sentAmount, sendCurrency }),
    basis: 'exact', low: null, high: null,
  }));
  return { items, values: items.map((i) => i.value), dataQuality: qualityOf(rows) };
}

/* Classify a set of rows by provenance. Null for an empty pool — "no data" is
   not a quality claim. */
function qualityOf(rows) {
  if (!rows || !rows.length) return null;
  const real = rows.filter((r) => r.is_indicative === false).length;
  if (real === rows.length) return 'real';
  return real === 0 ? 'indicative' : 'mixed';
}

/* Returns the comparable values (with the bank behind each) for a product, or
   null when Supabase isn't configured.
   Shape: { items:[{bank,value,basis,low,high,index,indexValue,spread,rateType}], values:[], dataQuality }.
   basis: 'exact' | 'range' (value is the midpoint of low–high) | 'from' (a floor). */
export async function getProductValues(country, product, currency, variant, opts = {}) {
  if (!isSupabaseConfigured) return null;
  const meta = getProduct(product);
  const pack = (items, rows = []) => ({
    items,
    values: items.map((i) => i.value),
    // 'real' | 'indicative' | 'mixed' | null — see REAL_ONLY. Callers must pass
    // this through so a generated figure is never rendered as a sourced one.
    dataQuality: qualityOf(rows),
  });
  if (!meta) return pack([]);

  if (meta.family === 'crossborder') {
    return getCrossBorderCostPool(country, opts);
  }
  const rows = await getGenericRates(country, product, currency, variant);
  return pack((rows || []).map((r) => ({
    bank: r.bank || null,
    value: Number(r.rate),
    basis: r.rate_basis || 'exact',
    low: r.rate_low == null ? null : Number(r.rate_low),
    high: r.rate_high == null ? null : Number(r.rate_high),
    // Floating rates (supabase/floating_rate.sql): what the loan tracks and the
    // bank's margin over it. `value` stays the all-in comparable figure; these
    // let the UI show that it is a formula, not a promise.
    index: r.rate_index || null,
    indexValue: r.index_value == null ? null : Number(r.index_value),
    spread: r.spread == null ? null : Number(r.spread),
    // 'apr' | 'yield' | 'flat'. Flat means interest on the ORIGINAL sum for the
    // whole tenor — about half the effective rate for the same money — so it
    // must be labelled wherever it is shown.
    rateType: r.rate_type || null,
  })), rows || []);
}

/* Benchmark summary for a rate product: masks bank identities (per the product's
   reveal-on-CTA model) and returns best / median / market-typical figures.
   Delegates value extraction to getProductValues (correct field per product) and
   the maths to benchmarkValues (the single canonical benchmarking path). */
export async function getRateBenchmark(country, product, currency) {
  const meta = getProduct(product);
  if (!meta) return null;
  const data = await getProductValues(country, product, currency);
  if (!data || !data.values.length) return null;

  const b = benchmarkValues(data.values, { rateType: meta.rateType });
  if (!b) return null;
  const bestItem = pickBestItem(data.items, meta.rateType);
  return {
    country,
    product,
    currency: currency || null,
    poolSize: b.poolSize,
    best: b.best,
    // 'exact' | 'range' (best is a midpoint — show "~") | 'from' (a floor).
    bestBasis: bestItem?.basis || 'exact',
    approxPool: (data.items || []).some((i) => i.basis && i.basis !== 'exact'),
    median: b.median,
    marketTypical: b.marketTypical,
    unit: meta.unit,
    benchmarkMasked: true,
    dataQuality: data.dataQuality,
    note: data.dataQuality === 'real'
      ? 'Sourced benchmark. Provider identities revealed after a connection request.'
      : 'Indicative benchmark — not sourced from published rates. Provider identities revealed after a connection request.',
  };
}
